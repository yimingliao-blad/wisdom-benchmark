"""The plan's scope numbers, DERIVED from the roster — never typed into prose.

Owner, 2026-08-09: "I have provide you a 25 model list, make the current project can work on the
list no matter what i ask you to do."

Decoupling the CODE from the model list was the easy half and it is done. The half that actually
rots is the PLAN: `~3,700 paid calls, ~$31`, `37 models x 100 items`, `3 models of 34`. Those were
true of a roster that no longer exists, and prose does not notice when its subject changes. A reader
next session inherits them as current.

So the numbers are generated from the roster and checked, and any measured CLAIM that was taken over
a different roster has to say so.

    python3 survey/plan_scope.py --roster survey/roster_25.json --items runs/fx_items_110.json
    python3 survey/plan_scope.py ... --check plans/openrouter-output-integrity/plan.md

`--check` exits 1 when the block in the document does not match what the roster produces now. It is
wired into the test suite, so changing the model list and forgetting the plan fails a test instead of
quietly publishing a stale scope.

Offline. No network. No spend.
"""
import argparse
import json
import os
import re
import statistics as st
import sys

BEGIN = "<!-- GEN:plan-scope -->"
END = "<!-- /GEN:plan-scope -->"


class ScopeError(RuntimeError):
    pass


def measured_tokens(records_path):
    """Mean prompt/completion tokens per model from a real run, for costing. None if unavailable."""
    if not records_path or not os.path.exists(records_path):
        return {}, None
    by = {}
    for line in open(records_path, encoding="utf-8"):
        if not line.strip():
            continue
        r = json.loads(line)
        if r.get("ok") and r.get("usage"):
            by.setdefault(r["model"], []).append((r["usage"].get("prompt_tokens", 0),
                                                  r["usage"].get("completion_tokens", 0)))
    if not by:
        return {}, None
    fleet = (st.mean([p for v in by.values() for p, _ in v]),
             st.mean([c for v in by.values() for _, c in v]))
    return by, fleet


def ever_observed(runs_glob):
    """Which models have EVER produced a real answer here, across every run.

    Deliberately NOT the same set as the costing source. Costing reads one arm's run; coverage asks
    a different question -- has this model ever been seen at all? Reading both off one file makes a
    model that was measured in another arm look unmeasured, and the warning it prints would be
    wrong. (Caught when the two counts came out 7 and 8.)
    """
    import glob
    seen = set()
    for p in glob.glob(runs_glob):
        for line in open(p, encoding="utf-8"):
            if not line.strip():
                continue
            r = json.loads(line)
            if r.get("completeness") not in ("PROVIDER_ERROR", "TRANSPORT_ERROR"):
                seen.add(r["model"])
    return seen


def compute(roster, n_items, arms, records_path=None, runs_glob=None, bench="futurex"):
    by, fleet = measured_tokens(records_path)
    seen_anywhere = ever_observed(runs_glob) if runs_glob else set(by)
    units = len(roster) * n_items * len(arms)
    cost, n_est = 0.0, 0
    for m in roster:
        obs = by.get(m["id"])
        if not obs:
            n_est += 1
        if fleet is None and not obs:
            continue
        p, c = ((st.mean([x for x, _ in obs]), st.mean([x for _, x in obs])) if obs else fleet)
        cost += (p / 1e6 * m["in"] + c / 1e6 * m["out"]) * n_items * len(arms)
    return {"bench": bench,
            "n_models": len(roster), "n_items": n_items, "arms": list(arms), "n_units": units,
            "projected_cost": round(cost, 2) if fleet else None,
            "n_models_unpriced_by_measurement": n_est,
            # coverage across EVERY run, not just the costing source -- see ever_observed()
            "never_measured": sorted(m["id"] for m in roster if m["id"] not in seen_anywhere),
            "n_open": sum(1 for m in roster if m.get("weights") == "open"),
            "n_series": len({m.get("series") for m in roster})}


def render_stages(stages, roster_path, n_models, n_open, n_series):
    """One block for the WHOLE experiment, not one arm.

    The BTF-3 arms were left carrying cost estimates from the superseded roster while the FutureX
    arm was regenerated -- so the plan's own total was part-derived and part-stale, with nothing
    saying which was which. A scope that covers only the arm someone remembered to rebuild is the
    same staleness the generator exists to prevent.
    """
    tot_units = sum(s["n_units"] for s in stages)
    tot_cost = sum(s["projected_cost"] or 0 for s in stages)
    any_cost = any(s["projected_cost"] is not None for s in stages)
    lines = [
        BEGIN,
        f"<!-- generated by survey/plan_scope.py from {roster_path} — do not hand-edit -->",
        "",
        f"**Run scope — derived from the roster, not typed here.** {n_models} models "
        f"({n_open} open-weight, {n_models - n_open} closed, {n_series} families) across "
        f"{len(stages)} arm(s): **{tot_units:,} units**"
        + (f", projected **${tot_cost:,.2f}**." if any_cost else "."),
        "",
        "| arm | bench | items | units | projected | costed from |",
        "|---|---|---:|---:|---:|---|",
    ]
    for s in stages:
        cost = f"${s['projected_cost']:,.2f}" if s["projected_cost"] is not None else "—"
        basis = (f"{s['n_models'] - s['n_models_unpriced_by_measurement']}/{s['n_models']} measured"
                 if s["projected_cost"] is not None else "no measurement yet")
        lines += [f"| `{', '.join(s['arms'])}` | {s['bench']} | {s['n_items']} | {s['n_units']:,} "
                  f"| {cost} | {basis} |"]
    lines += ["", f"**Total {tot_units:,} units"
                  + (f", ${tot_cost:,.2f}" if any_cost else "") + ".**", ""]
    lines.append(END)
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--roster", required=True)
    ap.add_argument("--items", required=True,
                    help="the item corpus for the FIRST stage (kept for single-arm use)")
    ap.add_argument("--arms", default="original")
    ap.add_argument("--bench", default="futurex")
    ap.add_argument("--stage", action="append", default=[], metavar="BENCH:ITEMS:ARMS[:RECORDS]",
                    help="an additional arm of the SAME experiment, repeatable. Given any --stage, "
                         "the block covers every stage and the plan's total is the whole run, not "
                         "the one arm someone remembered to rebuild.")
    ap.add_argument("--records", default=None, help="a run's records.jsonl, for measured token costs")
    ap.add_argument("--runs-glob", default=None,
                    help="e.g. 'runs/or_*/records.jsonl' -- EVERY run, for the has-this-model-ever-"
                         "been-observed coverage warning. A different question from --records.")
    ap.add_argument("--check", default=None, metavar="DOC",
                    help="verify DOC's generated block matches; exit 1 if it drifted")
    ap.add_argument("--write", default=None, metavar="DOC",
                    help="replace DOC's generated block in place")
    a = ap.parse_args()

    roster = json.load(open(a.roster))
    specs = [(a.bench, a.items, a.arms, a.records)]
    for raw in a.stage:
        parts = raw.split(":")
        if len(parts) not in (3, 4):
            raise ScopeError(f"--stage must be BENCH:ITEMS:ARMS[:RECORDS], got {raw!r}")
        specs.append((parts[0], parts[1], parts[2], parts[3] if len(parts) == 4 else None))
    stages = []
    for bench, items_path, arms, rec in specs:
        if not os.path.exists(items_path):
            raise ScopeError(f"{items_path} does not exist -- a stage cannot be scoped without its "
                             f"item corpus, and guessing its size would defeat the point")
        stages.append(compute(roster, len(json.load(open(items_path))), arms.split(","),
                              rec, a.runs_glob, bench=bench))
    s = stages[0]
    block = render_stages(stages, os.path.relpath(a.roster), s["n_models"], s["n_open"],
                          s["n_series"])

    for doc in (a.check, a.write):
        if not doc:
            continue
        body = open(doc, encoding="utf-8").read()
        if BEGIN not in body or END not in body:
            raise ScopeError(f"{doc} has no {BEGIN} ... {END} region. The scope numbers must live in "
                             f"a generated block, or they go stale the next time the roster moves.")
        cur = body[body.index(BEGIN):body.index(END) + len(END)]
        if doc == a.check:
            if cur.strip() != block.strip():
                raise ScopeError(
                    f"{doc}'s scope block does NOT match the current roster.\n"
                    f"--- the document says ---\n{cur}\n"
                    f"--- the roster produces ---\n{block}\n"
                    f"Re-run with --write {doc}.")
            print(f"  OK: {doc} matches {os.path.relpath(a.roster)} "
                  f"({s['n_models']} models, {len(stages)} arm(s), "
                  f"{sum(x['n_units'] for x in stages):,} units)")
        else:
            open(doc, "w", encoding="utf-8").write(body.replace(cur, block))
            print(f"  WROTE the scope block into {doc}")
    if not a.check and not a.write:
        print(block)


if __name__ == "__main__":
    try:
        main()
    except ScopeError as e:
        raise SystemExit(f"HALT: {e}")
